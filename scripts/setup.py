def install_and_start(root: Path, db_choice: dict | None = None) -> bool:
    """Local dev mode:
    - DB ใน Docker (container เดิมหรือใหม่) หรือข้ามถ้าไม่ต้องการ
    - Backend รันบนเครื่อง (uvicorn --reload)
    - Frontend รันบนเครื่อง (npm run dev)
    """
    if db_choice is None:
        db_choice = {"skip": False, "use_existing": False,
                     "host": "localhost", "port": 5432, "pg_user": "postgres"}

    skip_db = db_choice.get("skip", False)

    print("── เริ่มต้น project (Local Dev mode) ────────────────────")
    print()
    if skip_db:
        print("   DB       → ข้าม")
    elif db_choice.get("existing_database"):
        print(
            "   DB       → existing database "
            f"({db_choice['host']}:{db_choice['port']}/{db_choice['db_name']})"
        )
    elif db_choice.get("native"):
        print(f"   DB       → ใช้ native PostgreSQL (host=localhost:{db_choice.get('port', 5432)})")
    elif db_choice.get("use_existing"):
        print(f"   DB       → ใช้ container '{db_choice['container_name']}' (port {db_choice['port']})")
    else:
        print("   DB       → Docker container ใหม่")
    print("   Backend  → local (uvicorn --reload)")
    print("   Frontend → local (npm run dev)")
    print()

    docker_dir = root / "docker"
    backend_dir = root / "backend"
    frontend_dir = root / "frontend"
    db_name = root.name.lower().replace(" ", "_").replace("-", "_")
    db_name = re.sub(r"[^a-z0-9_]", "_", db_name)
    # อ่าน db_name จริงจาก .env
    env_file = backend_dir / ".env"
    if env_file.exists():
        for line in env_file.read_text(encoding="utf-8").splitlines():
            if line.startswith("DB_NAME="):
                db_name = line.split("=", 1)[1].strip()
                break

    # 1. npm install — NON-FATAL. A transient failure (flaky registry, or an
    # OneDrive sync lock on the just-extracted tree) must NOT abort the whole
    # setup and leave a DB-less, un-seedable project: the backend + DB + seed
    # below are what actually gate login, and the frontend deps can be
    # installed later with a plain `npm install`. Retry once, then continue
    # regardless. (Dogfood 2026-06-01: npm failed here → setup returned early
    # → no DB/admin → user stuck at "can't log in".)
    print("   📦 ติดตั้ง frontend dependencies...")
    code = _run_visible(["npm", "install"], cwd=frontend_dir)
    if code != 0:
        print("   ⚠️  npm install รอบแรกไม่ผ่าน — ลองใหม่อีกครั้ง...")
        code = _run_visible(["npm", "install"], cwd=frontend_dir)
    npm_ok = code == 0
    if npm_ok:
        print("   ✅ npm install เสร็จ")
    else:
        print("   ⚠️  npm install ยังไม่ผ่าน — ข้ามไปก่อน (ไม่บล็อก DB/seed)")
        print("      รันเองภายหลัง: cd frontend && npm install")
        print("      ถ้าโปรเจกต์อยู่ใน OneDrive: pause sync ชั่วคราวแล้วลองใหม่")
    print()

    # 2. pip install backend
    print("   🐍 ติดตั้ง backend dependencies...")
    pip_ok = False
    # ใช้ sys.executable เพื่อให้ install ใน Python environment เดียวกับที่รัน script นี้
    # ลอง install แบบ editable ก่อน
    code = _run_visible([sys.executable, "-m", "pip", "install", "-e", ".[dev]"], cwd=backend_dir)
    if code != 0:
        # ถ้าล้มเหลว ลอง install แบบปกติ (ไม่ editable) สำหรับ Anaconda
        print("   ⚠️  Editable install ล้มเหลว — ลอง regular install...")
        code = _run_visible(
            [sys.executable, "-m", "pip", "install",
             "fastapi", "uvicorn[standard]", "pydantic", "pydantic-settings",
             "sqlalchemy[asyncio]", "asyncpg", "alembic", "httpx",
             "python-jose[cryptography]", "passlib[bcrypt]", "msal", "anthropic",
             "structlog", "apscheduler", "prometheus-fastapi-instrumentator", "slowapi"],
            cwd=backend_dir,
        )
    if code == 0:
        pip_ok = True
        print("   ✅ pip install เสร็จ")
    else:
        print("   ❌ pip install ล้มเหลว")
        print("      รันเองด้วย: cd backend && pip install -e .[dev]")
