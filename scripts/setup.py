def _set_env_value(env_file: Path, key: str, value: str) -> None:
    """อัปเดต (หรือเพิ่ม) บรรทัด `key=value` ใน .env file"""
    if not env_file.exists():
        return
    lines = env_file.read_text(encoding="utf-8").splitlines()
    prefix = f"{key}="
    for i, line in enumerate(lines):
        if line.startswith(prefix):
            lines[i] = f"{key}={value}"
            break
    else:
        lines.append(f"{key}={value}")
    env_file.write_text("\n".join(lines) + "\n", encoding="utf-8")


def register_project(cfg: ProjectConfig, db_choice: dict, root: Path) -> None:
    """ส่ง registration ไป CT App Registry — เฟส 1 onboarding (ครั้งเดียวตอนตั้ง app).

    ดู docs/ops/registry.md §3:
    - endpoint `POST /api/v1/projects/register` เปิด — ไม่ต้องแนบ auth header
    - response 201 คืน `apiKey` ครั้งเดียว → เขียนกลับลง backend/.env ทันที
    - app จะอยู่สถานะ `pending` จนกว่า registry admin จะ approve
    ข้ามถ้า REGISTRY_URL ว่าง (registry ยังไม่ deploy — register ด้วยมือทีหลัง)
    """
    import urllib.error
    import urllib.request
    import json as json_mod

    # อ่าน REGISTRY_URL จาก backend/.env
    env_file = root / "backend" / ".env"
    registry_url = ""
    if env_file.exists():
        for line in env_file.read_text(encoding="utf-8").splitlines():
            if line.startswith("REGISTRY_URL="):
                registry_url = line.split("=", 1)[1].strip()

    if not registry_url:
        print("   ⏭️  ข้าม CT App Registry (REGISTRY_URL ว่าง)")
        print("      ตั้งค่าที่ backend/.env แล้ว register ด้วยมือ (ดู docs/ops/registry.md §3)")
        return

    # payload — camelCase ตาม docs/ops/registry.md §3.1
    # ไม่ส่ง backendUrl เพราะตอน setup ยังไม่รู้ production URL —
    # เพิ่มทีหลังผ่าน PATCH /projects/{slug} เพื่อเปิด health monitor (§4.1)
    payload = {
        "slug": cfg.project_slug,
        "displayName": cfg.project_display_name,
        "ownerEmail": cfg.owner,
        "businessUnit": cfg.bu,
        "authScope": cfg.auth_scope,
        "defaultLanguage": cfg.default_language,
        "techStack": {"backend": "FastAPI", "frontend": "React+TS", "db": "PostgreSQL"},
    }

    url = f"{registry_url.rstrip('/')}/api/v1/projects/register"
    data = json_mod.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        url, data=data,
        headers={"Content-Type": "application/json"},  # เปิด — ไม่แนบ X-API-Key
        method="POST",
    )

    try:
        with urllib.request.urlopen(req, timeout=10) as resp:
            body = json_mod.loads(resp.read().decode("utf-8"))
        api_key = body.get("apiKey", "")
        if api_key:
            _set_env_value(env_file, "REGISTRY_API_KEY", api_key)
            print("   ✅ ลงทะเบียนแล้ว — apiKey ถูกเขียนลง backend/.env (REGISTRY_API_KEY)")
        else:
            print("   ✅ ลงทะเบียนแล้ว — response ไม่มี apiKey, ตรวจสอบกับ admin")
        print("   ⏳ สถานะ: pending — ติดต่อ registry admin (ป่าน/IT) เพื่อ approve")
        print("      telemetry push จะได้ 403 จนกว่าจะ approve (เป็นเรื่องปกติ)")
    except urllib.error.HTTPError as e:
        if e.code == 409:
            print(f"   ℹ️  slug '{cfg.project_slug}' เคยลงทะเบียนแล้ว — ใช้ API key เดิม")
        else:
            print(f"   ⚠️  Registry ตอบ {e.code} — registration ไม่สำเร็จ")
            print("      ดู docs/ops/registry.md §6 แล้ว register ใหม่ด้วยมือ")
    except Exception as e:
        print(f"   ⚠️  ส่ง registration ไม่สำเร็จ: {e}")
        print("      register ใหม่ได้เมื่อ CT App Registry พร้อม (ดู docs/ops/registry.md §3)")


