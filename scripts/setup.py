def choose_database(
    default_db_name: str,
    env: EnvCheck | None = None,
    auth_required: bool = False,
) -> dict:
    print()
    print("── Database ──────────────────────────────────────────────")
    print()

    # Login ต้องใช้ DB (users / roles / permissions / app_settings / sessions).
    # ถ้า wizard ก่อนหน้านี้ตอบว่าใช้ auth → ห้ามข้าม DB เพราะ project จะ boot
    # ไม่ติดและ login เป็นไปไม่ได้
    if auth_required:
        print("   🔐 Login เปิดใช้งานอยู่ — Database จำเป็น (users / roles / sessions)")
