# ───────────────────────────────────────────────────────────────
# Target-dir resolution (Layout A vs sibling-zip)
# ───────────────────────────────────────────────────────────────
#
# Two supported layouts:
#
#   Layout A (default):
#       my-app/                      ← project root = template copy
#         AGENTS.md, scripts/setup.py, ...
#       User: copy template → cd my-app → run scripts/setup.py
#       Target dir = script_path.parent.parent (the template copy itself)
#
#   Sibling-zip (advanced):
#       parent/
#         web-app-standard/          ← unchanged template (read-only)
#           scripts/setup.py
#         my-app/                    ← empty / fresh project dir
#       User: cd my-app → run ../web-app-standard/scripts/setup.py
#                         --project-dir .
#       Target dir = the sibling project dir (cwd, or --project-dir)
#
# The bug: without --project-dir, sibling-zip layout makes
# `script_path.parent.parent` resolve to web-app-standard/ — the
# scaffolder would then write project.config, .env, backend/ etc. into
# the template repo itself, leaving my-app/ empty.


def _is_template_dir(path: Path) -> bool:
    """True if `path` is the canonical upstream web-app-standard repo.

    Heuristic: template-shaped files PLUS a .git/config whose remote URL
    looks like the CT-IT-Center upstream. Layout-A copies (made with
    `robocopy ... /XD .git`) have no .git and pass this check, even though
    they have setup.py/scaffold.py/AGENTS.md copied in.

    A user who clones a fork has a fork remote, not the canonical upstream
    → not detected → allowed. Only refused: someone running scripts/setup.py
    directly against an actual clone of CT-IT-Center/WEB-APP-STANDARD.
    """
    has_template_shape = (
        (path / "scripts" / "setup.py").exists()
        and (path / "scripts" / "scaffold.py").exists()
        and (path / "AGENTS.md").exists()
    )
    if not has_template_shape:
        return False
    git_config = path / ".git" / "config"
    if not git_config.exists():
        return False
    try:
        cfg = git_config.read_text(encoding="utf-8", errors="ignore").lower()
    except OSError:
        return False
    return "web-app-standard" in cfg


def _looks_like_fresh_project_dir(path: Path) -> bool:
    """True if `path` is empty or contains only innocuous files.

    Used to auto-detect sibling-zip layout: if cwd is empty-ish and not
    the template, we can safely scaffold into it without prompting.
    """
    if not path.is_dir():
        return False
    allowed = {".git", ".gitignore", "README.md", ".gitkeep", ".DS_Store"}
    for entry in path.iterdir():
        if entry.name in allowed:
            continue
        return False
    return True


def _resolve_project_dir(
    script_path: Path, cli_arg: str | None
) -> tuple[Path, str]:
    """Decide which directory to scaffold into.

    Returns (target_dir, layout_description). Raises SystemExit on
    unrecoverable ambiguity / template-dir conflict.
    """
    standard_root = script_path.parent.parent  # web-app-standard/ when sibling-zip; project root when Layout A
    cwd = Path.cwd().resolve()

    # Explicit override wins
    if cli_arg is not None:
        target = Path(cli_arg).resolve()
        if not target.exists():
            print(f"❌ --project-dir ไม่มีอยู่: {target}")
            sys.exit(1)
        if _is_template_dir(target):
            print("❌ --project-dir ชี้ไปที่ web-app-standard template เอง")
            print(f"   target: {target}")
            print()
            print("   เลือกหนึ่งใน:")
            print("   - Layout A: copy template → cd เข้า copy → run scripts/setup.py")
            print("   - Sibling-zip: cd ไป my-app ใหม่ → run ../web-app-standard/scripts/setup.py --project-dir .")
            sys.exit(1)
        return target, "explicit --project-dir"

    # No CLI arg: detect layout
    # Case 1: script lives inside the project (Layout A)
    #   standard_root has AGENTS.md AND we are running from inside it
    #   → scaffold into standard_root (the user's copy of the template)
    if (standard_root / "AGENTS.md").exists() and not _looks_like_fresh_project_dir(standard_root):
        # Sub-case: cwd is a sibling fresh dir AND template is read-only?
        # If cwd != standard_root AND cwd looks fresh AND cwd is NOT the
        # template, prefer cwd (sibling-zip layout).
        if (
            cwd != standard_root
            and not _is_template_dir(cwd)
            and _looks_like_fresh_project_dir(cwd)
        ):
            return cwd, "sibling-zip (cwd is fresh, auto-detected)"
        # Default: Layout A — scaffold into the template copy
        return standard_root, "Layout A (script_path.parent.parent)"

    # Case 2: script's parent.parent doesn't even look like a template
    #   → fall back to cwd
    if cwd != standard_root and not _is_template_dir(cwd):
        return cwd, "cwd fallback"

    print("❌ ไม่สามารถหา project dir ที่ปลอดภัย")
    print(f"   script: {script_path}")
    print(f"   cwd:    {cwd}")
    print()
    print("   ใช้ --project-dir <path> เพื่อระบุ project dir โดยตรง")
    sys.exit(1)


