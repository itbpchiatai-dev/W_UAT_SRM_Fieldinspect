@dataclass
class EnvCheck:
    docker_cli_ok: bool = False  # docker binary present
    docker_engine_ok: bool = False  # docker daemon responding
    docker_ok: bool = False  # legacy combined flag (cli AND engine)
    docker_version: str = ""
    node_ok: bool = False
    node_version: str = ""
    python_ok: bool = False
    python_version: str = ""
    ports_ok: dict[int, bool] = field(default_factory=dict)
    port_conflicts: list[int] = field(default_factory=list)

    @property
    def native_pg_on_5432(self) -> bool:
        """True if port 5432 is in use (almost certainly native PostgreSQL).

        We don't try to probe the actual protocol — anyone listening on
        5432 is treated as a postgres-compatible server. This matches the
        existing port-check message ('PostgreSQL').
        """
        return 5432 in self.port_conflicts

    @property
    def can_proceed(self) -> bool:
        return self.docker_ok and self.node_ok and not self.port_conflicts


def check_environment() -> EnvCheck:
    print()
    print("🔍 ตรวจสอบ environment...")
    print()
    env = EnvCheck()

    # Docker
    code, out = _run(["docker", "--version"])
    env.docker_cli_ok = code == 0
    if env.docker_cli_ok:
        env.docker_version = out.split("version")[-1].strip().split(",")[0].strip()
        print(f"   Docker          ✅  {env.docker_version}")
    else:
        print("   Docker          ❌  ไม่พบ — ติดตั้ง Docker Desktop ก่อน")
        print("                       https://www.docker.com/products/docker-desktop/")

    # Docker running
    if env.docker_cli_ok:
        code, _ = _run(["docker", "info"])
        if code != 0:
            env.docker_engine_ok = False
            print("   Docker Engine   ❌  Docker ไม่ได้รัน — เปิด Docker Desktop ก่อน")
        else:
            env.docker_engine_ok = True
            print("   Docker Engine   ✅  running")

    # Combined flag — kept for backward compat with anything still reading it
    env.docker_ok = env.docker_cli_ok and env.docker_engine_ok

    # Node.js
    code, out = _run(["node", "--version"])
    env.node_ok = code == 0
    if env.node_ok:
        env.node_version = out.strip()
        # ตรวจ version >= 18
        try:
            major = int(env.node_version.lstrip("v").split(".")[0])
            if major < 18:
                env.node_ok = False
                print(f"   Node.js         ⚠️  {env.node_version} — ต้องการ v18+ "
                      f"(https://nodejs.org/)")
            else:
                print(f"   Node.js         ✅  {env.node_version}")
        except ValueError:
            print(f"   Node.js         ✅  {env.node_version}")
    else:
        print("   Node.js         ❌  ไม่พบ — ติดตั้งจาก https://nodejs.org/")

    # Python — require >= 3.12 (scaffold pins py3.12)
    code, out = _run(["python", "--version"])
    if code != 0:
        code, out = _run(["python3", "--version"])
    env.python_ok = code == 0
    if env.python_ok:
        env.python_version = out.strip()
        try:
            parts = env.python_version.replace("Python", "").strip().split(".")
            major, minor = int(parts[0]), int(parts[1])
            if (major, minor) < (3, 12):
                env.python_ok = False
                print(f"   Python          ❌  {env.python_version} — ต้องการ 3.12+ "
                      f"(scaffold pin python:3.12)")
            else:
                print(f"   Python          ✅  {env.python_version}")
        except (ValueError, IndexError):
            print(f"   Python          ✅  {env.python_version} (version parse skipped)")

    # Ports
    print()
    for port, name in REQUIRED_PORTS.items():
        in_use = _port_in_use(port)
        env.ports_ok[port] = not in_use
        if in_use:
            env.port_conflicts.append(port)
            print(f"   Port {port}       ⚠️  ถูกใช้งานอยู่ ({name})")
        else:
            print(f"   Port {port}       ✅  ว่าง ({name})")

    print()
    return env


def handle_env_issues(env: EnvCheck, *, database_mode: str = "new") -> bool:
    """Return True if can proceed.

    Docker policy:
    - Engine running → proceed (current behavior).
    - Engine NOT running BUT native PostgreSQL on 5432 → warn + proceed.
      The DB choose-flow will route to the "use native pg" branch.
    - Engine NOT running AND no native pg → hard fail (current behavior).

    Existing-database mode does not use Docker or create database objects,
    so Docker is optional in that mode.
    """
    if database_mode == "existing":
        if not env.docker_cli_ok or not env.docker_engine_ok:
            print("ℹ️  Existing database mode — ข้าม Docker requirement")
            print()
    elif not env.docker_cli_ok:
        print("❌ ต้องมี Docker Desktop ก่อน — ติดตั้งแล้วรัน script ใหม่")
        return False

    if database_mode != "existing" and not env.docker_engine_ok:
        if env.native_pg_on_5432:
            print("⚠️  Docker Engine ไม่ได้รัน แต่พบ PostgreSQL บน port 5432")
            print("   จะใช้ native PostgreSQL แทน Docker container")
            print("   (ถ้าต้องการใช้ Docker — เปิด Docker Desktop แล้วรัน script ใหม่)")
            print()
        else:
            print("❌ ต้องมี Docker Engine ก่อน — เปิด Docker Desktop แล้วรัน script ใหม่")
            return False

    if not env.node_ok:
        print("❌ ต้องมี Node.js v18+ ก่อน — ติดตั้งแล้วรัน script ใหม่")
        return False

    if env.port_conflicts:
        # Port 5432 is special: a busy 5432 almost always means an existing
        # PostgreSQL the user can reuse. Step 1b (choose-DB) detects that
        # server's real port and either reuses it or auto-picks a free port
        # (5433-5439) — so it is NEVER a blocking conflict and must not scare
        # the user with a default-No "proceed despite conflict?" gate.
        if 5432 in env.port_conflicts:
            print("ℹ️  Port 5432 ถูกใช้งานอยู่ — ไม่ใช่ปัญหา")
            print("   ขั้นตอนถัดไป (เลือก DB) จะตรวจว่ามี PostgreSQL ให้ reuse ไหม")
            print("   ถ้ามี → ใช้ตาม port ที่เจอ; ถ้าไม่มี → เสนอ port ว่างให้เลือก")
            print("   (กด Enter รับค่าที่เสนอ — wizard ไม่เลือก port เองโดยไม่ถาม)")
            print("   ทั้งสองทางจะตั้ง DB_PORT ใน .env ให้ตรง — ไม่ error ตอน start")
            print()

        # Backend/Frontend dev ports only matter when you later run the dev
        # server, not during setup itself. Warn, but don't block (default Yes).
        dev_conflicts = [p for p in env.port_conflicts if p != 5432]
        if dev_conflicts:
            print("⚠️  Port (dev server) ต่อไปนี้ถูกใช้งานอยู่:")
            for port in dev_conflicts:
                print(f"   {port} ({REQUIRED_PORTS[port]})")
            print("   • หยุด service ที่ใช้ port นั้น หรือแก้ port ใน docker-compose.yml ภายหลัง")
            print()
            if not _confirm("   ดำเนินการต่อ?", default_yes=True):
                return False

    return True



