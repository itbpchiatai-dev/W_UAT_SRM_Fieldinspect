def find_postgres_containers():
    """หา PostgreSQL containers ที่รันอยู่ พร้อม detect pg_user จริง"""
    # ใช้ --format แยก field ชัดเจน ไม่ใช้ | เพราะอาจอยู่ใน image name
    code, out = _run([
        "docker", "ps", "--filter", "status=running",
        "--format", "{{.Names}}\t{{.Image}}\t{{.Ports}}",
    ])
    if code != 0 or not out:
        return []

    containers = []
    for line in out.strip().split("\n"):
        if not line.strip():
            continue
        parts = line.split("\t")
        if len(parts) < 3:
            continue
        name, image, ports = parts[0].strip(), parts[1].strip(), parts[2].strip()

        # กรอง postgres/pgvector เท่านั้น
        if not ("postgres" in image.lower() or "pgvector" in image.lower()):
            continue

        # หา host port ที่ map ไป 5432
        port = 5432
        match = re.search(r":(\d+)->5432", ports)
        if match:
            port = int(match.group(1))

        # Detect postgres superuser จริงจาก container
        pg_user = _detect_pg_user(name)

        containers.append({
            "name": name,
            "image": image,
            "port": port,
            "pg_user": pg_user,
        })

    return containers


def _detect_pg_user(container_name: str) -> str:
    """ลอง connect จริงด้วย user ที่เป็นไปได้ คืน user แรกที่ connect สำเร็จ"""
    candidates = []

    # 1. ดู env ของ container ก่อน (น่าเชื่อถือที่สุด)
    # container_name comes from `docker ps`, but list-form is still safer
    # against an exotic image name that happens to contain shell metachars.
    code, out = _run(["docker", "exec", container_name, "env"])
    if code == 0:
        for line in out.splitlines():
            if line.startswith("POSTGRES_USER="):
                user = line.split("=", 1)[1].strip()
                if user and user not in candidates:
                    candidates.insert(0, user)
            elif line.startswith("PGUSER="):
                user = line.split("=", 1)[1].strip()
                if user and user not in candidates:
                    candidates.insert(0, user)

    # 2. fallback list
    for u in ["postgres", "admin", "root"]:
        if u not in candidates:
            candidates.append(u)

    # 3. ทดสอบ connect จริงทีละ user. List-form bypasses the shell —
    # the 2>&1 in the old string just merged streams, which _run already
    # does via capture_output → stdout+stderr concat.
    for user in candidates:
        code, out = _run(
            ["docker", "exec", container_name, "psql", "-U", user, "-c", "SELECT 1;"]
        )
        if code == 0 and "ERROR" not in out and "fatal" not in out.lower():
            return user

    # ไม่พบ user ที่ใช้ได้
    return ""


def _validate_ident(label: str, value: str) -> str:
    """Validate a PostgreSQL identifier (db / role name).

    Returns the value if valid. Calls sys.exit on rejection — we'd rather
    refuse to run than silently fall back to a less-safe escape. Identifiers
    must match ^[A-Za-z_][A-Za-z0-9_]*$ — this matches both the unquoted
    identifier rules of PostgreSQL and our scaffold's defaults (db_name is
    derived from the project slug with `-` → `_`).

    The constraint is documented at the _ask_db_credentials prompt (F1).
    """
    if not _IDENT_RE.match(value):
        print(f"   ❌ ค่า '{label}' ไม่ถูกต้อง: {value!r}")
        print(f"      ต้องขึ้นต้นด้วยตัวอักษรหรือ '_' ตามด้วย [A-Za-z0-9_] เท่านั้น")
        print(f"      (PostgreSQL identifier — กรุณาแก้แล้วรันใหม่)")
        sys.exit(1)
    return value


def _sql_quote_literal(value: str) -> str:
    """Escape a string literal for PostgreSQL — double single-quotes.

    Refuses backslashes outright; the standard_conforming_strings default
    means \\ is literal, but mixing this with E'...' strings elsewhere is
    a footgun. Passwords with `\\` need the user to pick a different one.
    """
    if "\\" in value:
        print("   ❌ Password มี '\\' — กรุณาเลือกค่าที่ไม่มี backslash")
        sys.exit(1)
    return value.replace("'", "''")


def _prompt_pg_superuser_password(pg_user: str) -> str:
    """Prompt for the postgres superuser password, then return it.

    Used only when PGPASSWORD is not already set in the env. We pass the
    captured value via env to subprocess.run so psql doesn't try to read
    its own tty prompt (which would deadlock under capture_output) — F3.
    """
    print(f"   🔐 psql connection ต้องการ password ของ superuser '{pg_user}'")
    try:
        # Echo '*' per char — stdlib getpass shows nothing on Windows and
        # users assume the wizard is hung when typing seems invisible.
        return _getpass_masked(f"      Password for {pg_user} (mask): ")
    except (KeyboardInterrupt, EOFError):
        print()
        print("   ❌ ยกเลิก — กรุณาตั้ง PGPASSWORD แล้วรันใหม่ หรือสร้าง user/database ด้วยมือ")
        sys.exit(1)


# SQL templates for the temp-file-based path (F1).
# We use psql -v variables which psql escapes server-side: `:'name'` is a
# literal (single-quoted, with escapes), `:"name"` is an identifier
# (double-quoted, with escapes). This is the canonical way to pass
# untrusted strings to psql without shell or SQL injection.
_CREATE_USER_SQL = r"""\
\set ON_ERROR_STOP on
SELECT EXISTS(SELECT 1 FROM pg_roles WHERE rolname = :'db_user') AS user_exists
\gset
\if :user_exists
    \echo 'EXISTS_USER'
\else
    CREATE USER :"db_user" WITH PASSWORD :'db_password';
    \echo 'CREATED_USER'
\endif
"""

_CREATE_DB_SQL = r"""\
\set ON_ERROR_STOP on
SELECT EXISTS(SELECT 1 FROM pg_database WHERE datname = :'db_name') AS db_exists
\gset
\if :db_exists
    \echo 'EXISTS_DB'
\else
    CREATE DATABASE :"db_name" OWNER :"db_user";
    \echo 'CREATED_DB'
\endif
"""

_GRANT_SQL = r"""\
\set ON_ERROR_STOP on
GRANT ALL PRIVILEGES ON DATABASE :"db_name" TO :"db_user";
"""

_CREATE_EXTENSION_SQL = r"""\
\set ON_ERROR_STOP on
CREATE EXTENSION IF NOT EXISTS :"ext_name";
"""


def _run_psql_script(
    psql_path: str,
    base_args: list[str],
    sql: str,
    variables: dict[str, str],
    env: dict[str, str] | None = None,
    db_name: str | None = None,
) -> tuple[int, str]:
    """Write `sql` to a temp file and run `psql -f <file>` with `-v` variables.

    Returns (returncode, combined-stdout+stderr). Caller inspects the
    output for the sentinel strings produced by `\\echo` in the script.

    Why temp file (not -c): -c is a single statement string that goes
    through the shell — any single quote in db_password / db_user (and
    any non-ascii) requires layered escaping. -f reads the script as a
    file (no shell involvement) and -v values are escaped server-side by
    psql when referenced as `:'name'` / `:"name"`.
    """
    fd, path = tempfile.mkstemp(suffix=".sql", text=True)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(sql)
        cmd_parts = [f'"{psql_path}"'] + base_args
        if db_name:
            cmd_parts.append(f'-d "{db_name}"')
        for key, val in variables.items():
            # psql -v key=value — psql parses the right-hand side itself;
            # the shell still sees this whole arg, so we wrap in quotes
            # and escape any embedded double-quote.
            safe = val.replace('"', '\\"')
            cmd_parts.append(f'-v {key}="{safe}"')
        cmd_parts.extend(["-f", f'"{path}"'])
        return _run(" ".join(cmd_parts), env=env)
    finally:
        try:
            os.unlink(path)
        except OSError:
            pass


def _create_database_native(pg_user: str, db_name: str,
                            db_user: str, db_password: str,
                            host: str = "localhost", port: int = 5432) -> bool:
    """Create user + database via host-side psql against a native PostgreSQL.

    Uses temp SQL files + psql -v server-side quoting (F1) to avoid shell /
    SQL injection through db_password / db_user / db_name. Existence
    checks use `psql -tA` + `SELECT EXISTS(...)` returning literally 't'
    or 'f' (F2). Prompts for PGPASSWORD when not set and forwards it via
    subprocess env (F3) so psql doesn't try to read its own tty under
    capture_output.

    Mirrors _create_database_in_container but uses `psql` on the host
    instead of `docker exec ... psql`. Requires `psql` on PATH (Windows
    installer adds C:\\Program Files\\PostgreSQL\\<ver>\\bin to PATH).

    Returns False if psql is missing or connect fails — caller prints
    fallback instructions.
    """
    import shutil

    psql = shutil.which("psql")
    if not psql:
        print("   ⚠️  psql not on PATH — ข้ามการสร้าง user/database อัตโนมัติ")
        print("      เพิ่ม C:\\Program Files\\PostgreSQL\\<ver>\\bin ลงใน PATH")
        print(f"      แล้วสร้างเองด้วย: psql -U {pg_user} -h {host} -p {port}")
        return False

    # F1: validate identifiers. psql escapes :"name" but identifiers with
    # `"` or non-ASCII cause confusing failures later — fail fast here.
    _validate_ident("pg_user", pg_user)
    _validate_ident("db_user", db_user)
    _validate_ident("db_name", db_name)

    # F3: ensure PGPASSWORD is set before any capture_output psql call,
    # otherwise psql blocks reading from its own tty (which is the
    # captured pipe) → infinite hang.
    env = os.environ.copy()
    if not env.get("PGPASSWORD"):
        env["PGPASSWORD"] = _prompt_pg_superuser_password(pg_user)

    base_args = [
        f"-U {pg_user}",
        f"-h {host}",
        f"-p {port}",
        "-w",  # never prompt for password — PGPASSWORD is set, or fail
    ]

    print(f"   🔍 ทดสอบ connection: native PostgreSQL host={host}:{port} user={pg_user}...")
    code, out = _run(
        f'"{psql}" {" ".join(base_args)} -tA -c "SELECT 1;"',
        env=env,
    )
    if code != 0 or "ERROR" in out or "fatal" in out.lower():
        print(f"   ❌ Connect ไม่ได้ด้วย user '{pg_user}'")
        print(f"      Error: {out[:200]}")
        return False
    print(f"   ✅ Connect สำเร็จ (superuser: {pg_user})")

    # CREATE USER — F2: existence check via `psql -tA -c "SELECT EXISTS(...)"`
    # returning exactly 't' or 'f' on stdout. Old code used `if "1" in out`
    # which tripped on stray stderr digits.
    user_exists_cmd = (
        f'"{psql}" {" ".join(base_args)} -tA -v db_user="{db_user}" '
        f'-c "SELECT EXISTS(SELECT 1 FROM pg_roles WHERE rolname = :\'db_user\');"'
    )
    code, out = _run(user_exists_cmd, env=env)
    if code == 0 and out.strip() == "t":
        print(f"   ✅ User '{db_user}' มีอยู่แล้ว")
    else:
        code, out = _run_psql_script(
            psql, base_args, _CREATE_USER_SQL,
            {"db_user": db_user, "db_password": db_password},
            env=env,
        )
        if code != 0 or "ERROR" in out:
            print(f"   ❌ สร้าง user ล้มเหลว: {out[:200]}")
            return False
        print(f"   ✅ สร้าง user '{db_user}' เสร็จ")

    # CREATE DATABASE
    db_exists_cmd = (
        f'"{psql}" {" ".join(base_args)} -tA -v db_name="{db_name}" '
        f'-c "SELECT EXISTS(SELECT 1 FROM pg_database WHERE datname = :\'db_name\');"'
    )
    code, out = _run(db_exists_cmd, env=env)
    if code == 0 and out.strip() == "t":
        print(f"   ✅ Database '{db_name}' มีอยู่แล้ว")
    else:
        code, out = _run_psql_script(
            psql, base_args, _CREATE_DB_SQL,
            {"db_name": db_name, "db_user": db_user},
            env=env,
        )
        if code != 0 or "ERROR" in out:
            print(f"   ❌ สร้าง database ล้มเหลว: {out[:300]}")
            return False
        print(f"   ✅ สร้าง database '{db_name}' เสร็จ")

    _run_psql_script(
        psql, base_args, _GRANT_SQL,
        {"db_name": db_name, "db_user": db_user},
        env=env,
    )

    # Extensions (require superuser; CREATE EXTENSION lives inside the new DB)
    extensions = ["uuid-ossp", "pgcrypto", "pg_trgm", "vector"]
    ok_exts, fail_exts = [], []
    for ext in extensions:
        code, out = _run_psql_script(
            psql, base_args, _CREATE_EXTENSION_SQL,
            {"ext_name": ext},
            env=env,
            db_name=db_name,
        )
        if code == 0 and "ERROR" not in out:
            ok_exts.append(ext)
        else:
            fail_exts.append(ext)
    if ok_exts:
        print(f"   ✅ Extensions: {', '.join(ok_exts)}")
    if fail_exts:
        print(f"   ⚠️  Extensions ไม่สำเร็จ: {', '.join(fail_exts)}")
    return True


def _docker_exec_psql_script(
    container_name: str, pg_user: str,
    sql: str, variables: dict[str, str],
    db_name: str | None = None,
) -> tuple[int, str]:
    """Run a SQL script inside a docker container's psql via stdin.

    Mirrors _run_psql_script but for the container variant — we pipe the
    script through `docker exec -i ... psql -f -` so the SQL never goes
    through a shell command-line. Variables are passed via psql -v and
    quoted server-side (`:'name'` / `:"name"`).

    Why stdin (not -c with a heredoc): keeps the same safety property as
    the native path — no untrusted string is ever interpolated into a
    shell command line.
    """
    cmd = ["docker", "exec", "-i", container_name, "psql", "-U", pg_user, "-w"]
    if db_name:
        cmd.extend(["-d", db_name])
    for key, val in variables.items():
        cmd.extend(["-v", f"{key}={val}"])
    cmd.extend(["-f", "-"])
    # subprocess.run with a list arg avoids shell interpolation entirely.
    # No shell=True here — that's the whole point.
    try:
        result = subprocess.run(
            cmd,
            input=sql,
            capture_output=True, text=True,
            encoding="utf-8", errors="replace",
        )
    except FileNotFoundError:
        return 127, "docker not found"
    return result.returncode, (result.stdout + result.stderr).strip()


def _create_database_in_container(container_name: str, pg_user: str,
                                   db_name: str, db_user: str,
                                   db_password: str) -> bool:
    """Create dedicated user + database inside a running postgres container.

    Uses `docker exec -i ... psql -f -` with psql -v server-side quoting
    (F1) so db_password / db_user / db_name never get interpolated into
    a shell command. Existence checks use `SELECT EXISTS(...)` returning
    literally 't' / 'f' (F2).

    pg_user  = superuser สำหรับสร้าง (เช่น postgres)
    db_user  = dedicated user สำหรับ app นี้โดยเฉพาะ
    db_password = password ของ db_user
    """
    # F1: validate identifiers.
    _validate_ident("pg_user", pg_user)
    _validate_ident("db_user", db_user)
    _validate_ident("db_name", db_name)

    # Step 1: ทดสอบ connect ด้วย superuser ก่อน
    print(f"   🔍 ทดสอบ connection: {container_name} user={pg_user}...")
    code, out = _run(
        f'docker exec {container_name} psql -U {pg_user} -tA -c "SELECT 1;"'
    )
    if code != 0 or "ERROR" in out or "fatal" in out.lower():
        print(f"   ❌ Connect ไม่ได้ด้วย user '{pg_user}'")
        print(f"      Error: {out[:200]}")
        return False
    print(f"   ✅ Connect สำเร็จ (superuser: {pg_user})")

    # Step 2: สร้าง dedicated user ถ้ายังไม่มี — F2: SELECT EXISTS → 't'/'f'
    code, out = _docker_exec_psql_script(
        container_name, pg_user,
        "\\set ON_ERROR_STOP on\n"
        "SELECT EXISTS(SELECT 1 FROM pg_roles WHERE rolname = :'db_user');\n",
        {"db_user": db_user},
    )
    # `psql -f -` prints a header — find the data row 't' or 'f'.
    user_exists = code == 0 and any(
        line.strip() == "t" for line in out.splitlines()
    )
    if user_exists:
        print(f"   ✅ User '{db_user}' มีอยู่แล้ว")
    else:
        code, out = _docker_exec_psql_script(
            container_name, pg_user, _CREATE_USER_SQL,
            {"db_user": db_user, "db_password": db_password},
        )
        if code != 0 or "ERROR" in out:
            print(f"   ❌ สร้าง user ล้มเหลว: {out[:200]}")
            return False
        print(f"   ✅ สร้าง user '{db_user}' เสร็จ")

    # Step 3: สร้าง database เจ้าของเป็น db_user
    code, out = _docker_exec_psql_script(
        container_name, pg_user,
        "\\set ON_ERROR_STOP on\n"
        "SELECT EXISTS(SELECT 1 FROM pg_database WHERE datname = :'db_name');\n",
        {"db_name": db_name},
    )
    db_exists = code == 0 and any(
        line.strip() == "t" for line in out.splitlines()
    )
    if db_exists:
        print(f"   ✅ Database '{db_name}' มีอยู่แล้ว")
    else:
        code, out = _docker_exec_psql_script(
            container_name, pg_user, _CREATE_DB_SQL,
            {"db_name": db_name, "db_user": db_user},
        )
        if code != 0 or "ERROR" in out:
            print(f"   ❌ สร้าง database ล้มเหลว: {out[:300]}")
            return False
        print(f"   ✅ สร้าง database '{db_name}' เสร็จ")

    # Step 4: Grant privileges
    _docker_exec_psql_script(
        container_name, pg_user, _GRANT_SQL,
        {"db_name": db_name, "db_user": db_user},
    )

    # Step 5: Extensions (ต้องใช้ superuser)
    extensions = ["uuid-ossp", "pgcrypto", "pg_trgm", "vector"]
    ok_exts, fail_exts = [], []
    for ext in extensions:
        code, out = _docker_exec_psql_script(
            container_name, pg_user, _CREATE_EXTENSION_SQL,
            {"ext_name": ext},
            db_name=db_name,
        )
        if code == 0 and "ERROR" not in out:
            ok_exts.append(ext)
        else:
            fail_exts.append(ext)

    if ok_exts:
        print(f"   ✅ Extensions: {', '.join(ok_exts)}")
    if fail_exts:
        print(f"   ⚠️  Extensions ไม่สำเร็จ: {', '.join(fail_exts)}")

    return True


def _prompt_identifier(question: str, default: str) -> str:
    """Prompt for a PostgreSQL identifier (DB / role name).

    Re-prompts until input matches ^[A-Za-z_][A-Za-z0-9_]*$ — same constraint
    enforced server-side by _validate_ident before we compose any SQL (F1).
    Documented here so users hit the message at prompt time, not later
    inside _create_database_*.
    """
    while True:
        value = _prompt(question, default=default)
        if _IDENT_RE.match(value):
            return value
        print(f"   ⚠️  '{value}' ไม่ใช่ PostgreSQL identifier ที่ใช้ได้")
        print(f"      ต้องขึ้นต้นด้วยตัวอักษรหรือ '_' ตามด้วย [A-Za-z0-9_] เท่านั้น")


def _ask_db_credentials(default_db_name: str) -> dict:
    """ถามและให้แก้ไข DB name / user / password ก่อนสร้าง.

    Identifier constraint (db_name / db_user, F1):
        ต้องขึ้นต้นด้วยตัวอักษรหรือ '_' ตามด้วย [A-Za-z0-9_] เท่านั้น —
        psql ใช้ค่านี้สร้าง role / database จริง ๆ ค่าที่ผิด regex จะถูก
        ปฏิเสธก่อน compose SQL (กัน SQL injection / shell injection).

    Password rules (F1):
        - ห้ามมี backslash (`\\`) — ปฏิเสธทันทีเพื่อกัน escape ที่ซับซ้อน.
        - Single quote `'` รับได้ — escape เป็น `''` ตอน compose SQL.
    """
    # สร้าง short name จาก default (ตัด _portal, _system, _app ออก)
    short = default_db_name
    for suffix in ["_executive_intelligence_portal", "_intelligence_portal",
                   "_executive_portal", "_portal", "_system", "_app", "_api"]:
        if short.endswith(suffix):
            short = short[:-len(suffix)]
            break
    # ตัดให้สั้นลง ไม่เกิน 20 chars
    if len(short) > 20:
        short = short[:20].rstrip("_")

    # Generate a unique dev password per scaffold run so two projects on the
    # same dev host never collide on a shared static credential.
    generated_password = _gen_dev_db_password()

    print()
    print("   ค่า default (กด Enter เพื่อใช้):")
    print(f"   DB Name:     {default_db_name}")
    print(f"   DB User:     {short}")
    print(f"   DB Password: {generated_password}  (random, สำหรับ dev เท่านั้น)")
    print()

    if not _confirm("   แก้ไขค่าเหล่านี้?", default_yes=False):
        return {
            "db_name": default_db_name,
            "db_user": short,
            "db_password": generated_password,
        }

    print()
    # Identifier: validate (F1) — refuse anything outside [A-Za-z_][A-Za-z0-9_]*
    db_name = _prompt_identifier("   DB Name", default=default_db_name)
    db_user = _prompt_identifier("   DB User", default=short)
    # Password: reject backslashes (F1) — see _sql_quote_literal docstring.
    while True:
        db_password = _prompt("   DB Password", default=generated_password)
        if "\\" not in db_password:
            break
        print("   ⚠️  Password มี '\\' — กรุณาเลือกค่าที่ไม่มี backslash")

    return {
        "db_name": db_name,
        "db_user": db_user,
        "db_password": db_password,
    }


