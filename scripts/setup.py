def _resolve_argv(cmd: str | list[str]) -> str | list[str]:
    """Resolve a list command's executable to its full path.

    On Windows, tools like `npm`/`npx` ship as `npm.CMD` and CreateProcess
    (shell=False) does NOT search PATHEXT — so a bare ``["npm", ...]`` raises
    FileNotFoundError even though npm is on PATH (this is exactly what crashed
    the wizard at the frontend-install step on every Windows machine).
    ``shutil.which()`` DOES honour PATHEXT and returns the full ``npm.CMD``
    path, which subprocess can launch with shell=False — keeping the no-shell
    policy (audit #4). Str commands (shell=True) are returned unchanged; a
    name we can't resolve is left as-is so the caller still sees the failure.
    """
    import shutil
    if isinstance(cmd, list) and cmd:
        exe = shutil.which(cmd[0])
        if exe:
            return [exe, *cmd[1:]]
    return cmd


def _run(
    cmd: str | list[str],
    cwd: Path | None = None,
    capture: bool = True,
    env: dict[str, str] | None = None,
) -> tuple[int, str]:
    """Run a command and capture stdout+stderr.

    Prefer list-form argv when possible — it skips the shell entirely
    (no quoting / no command-injection surface). Pass a str only when
    you need shell features (pipes, redirects, builtins like `start`);
    we honour shell=True only in that case. See audit finding #4.

    encoding='utf-8' + errors='replace' avoids the Windows cp1252 decode
    crash when psql/docker emit utf-8 bytes (postgres locale messages,
    container labels, Thai user input echoed back) — see F4.
    """
    cmd = _resolve_argv(cmd)
    use_shell = isinstance(cmd, str)
    try:
        result = subprocess.run(
            cmd, shell=use_shell, cwd=cwd,
            capture_output=capture, text=True,
            encoding="utf-8", errors="replace",
            env=env,
        )
    except FileNotFoundError as exc:
        # Executable not on PATH — return a non-zero code instead of raising
        # so callers degrade gracefully rather than crashing the whole setup.
        return 127, str(exc)
    return result.returncode, (result.stdout + result.stderr).strip()


def _run_visible(cmd: str | list[str], cwd: Path | None = None) -> int:
    """Run command with visible output. Same str-vs-list policy as _run."""
    cmd = _resolve_argv(cmd)
    try:
        result = subprocess.run(cmd, shell=isinstance(cmd, str), cwd=cwd)
    except FileNotFoundError:
        # Missing executable → non-zero code, never raise (audit/dogfood
        # 2026-06-01: a bare ["npm", ...] used to raise here and abort setup).
        return 127
    return result.returncode


def _port_in_use(port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        return s.connect_ex(("127.0.0.1", port)) == 0


def _suggest_free_db_port(env: "EnvCheck | None" = None,
                          start: int = 5433, end: int = 5439) -> int:
    """Find the first free port for a new postgres dev container.

    Walks `start..end` (inclusive), skipping anything we already know is
    in use. Falls back to 5435 if nothing in range is free — the user
    can still override at the prompt.
    """
    known_busy = set(env.port_conflicts) if env else set()
    for port in range(start, end + 1):
        if port in known_busy:
            continue
        if _port_in_use(port):
            continue
        return port
    return 5435


def _ask_new_container_port(env: "EnvCheck | None" = None) -> int:
    """Resolve the host port for a freshly-created DB container.

    If 5432 is free we just take it (the convention, matches every doc).
    If 5432 is busy we surface the conflict, scan 5433-5439 for a free
    port, and prompt the user — defaulting to that suggestion so a plain
    Enter is the right answer. The wizard never silently picks a non-
    default port that would later mismatch the .env / compose mapping.
    """
    if not _port_in_use(5432) and not (env and 5432 in env.port_conflicts):
        return 5432
    suggested = _suggest_free_db_port(env)
    print()
    print(f"   ⚠️  Port 5432 ถูกใช้งานอยู่ — DB container ใหม่ต้องใช้ port อื่น")
    print(f"      port ว่างถัดไปที่เจอ: {suggested}")
    while True:
        raw = input(f"   Port สำหรับ DB container ใหม่ [default: {suggested}]: ").strip()
        if not raw:
            return suggested
        try:
            chosen = int(raw)
        except ValueError:
            print("   ⚠️  ใส่ตัวเลขเท่านั้น")
            continue
        if not (1024 <= chosen <= 65535):
            print("   ⚠️  port ต้องอยู่ระหว่าง 1024-65535")
            continue
        if _port_in_use(chosen):
            print(f"   ⚠️  port {chosen} ก็ถูกใช้งานอยู่ — ลองอันอื่น")
            continue
        return chosen


def _slug_from_folder(folder_name: str) -> str:
    """Convert folder name to kebab-case slug."""
    slug = folder_name.lower()
    slug = re.sub(r"[^a-z0-9]+", "-", slug)
    slug = slug.strip("-")
    return slug[:50]


def _prompt(question: str, default: str = "", required: bool = True) -> str:
    while True:
        hint = f" [{default}]" if default else ""
        answer = input(f"{question}{hint}: ").strip()
        if not answer and default:
            return default
        if not answer and required:
            print("    ⚠️  กรุณาระบุค่า")
            continue
        return answer


def _confirm(question: str, default_yes: bool = True) -> bool:
    hint = "Y/n" if default_yes else "y/N"
    answer = input(f"{question} [{hint}]: ").strip().lower()
    if not answer:
        return default_yes
    return answer in ("y", "yes")


