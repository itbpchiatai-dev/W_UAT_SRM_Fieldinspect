def _spawn_dev_servers(root: Path, db_choice: dict | None) -> bool:
    """Open backend + frontend in their own terminal windows so the user
    sees logs side-by-side instead of having to copy/paste commands.

    Returns True if both windows were spawned, False if the platform isn't
    supported or spawning failed (caller falls back to printed instructions).

    Why two windows: uvicorn --reload and `npm run dev` are long-running
    foreground processes — they can't share a single terminal without
    losing log clarity. We hand each its own window and let the OS handle
    process management. setup.py exits as soon as both are launched.

    Windows: `start "Title" cmd /k <cmd>` — start is a cmd builtin so it
        needs shell=True. /k keeps the window open after the command exits
        (so a crash leaves logs visible).
    macOS:   osascript drives Terminal.app to open a new window and run
        the command. iTerm users get the system Terminal — close enough.
    Linux:   try common terminal emulators in order; bail if none found.
        Wayland users on a non-GNOME desktop may not have a default and
        will need to launch by hand — we print instructions then.
    """
    backend_dir = root / "backend"
    frontend_dir = root / "frontend"
    db_port = db_choice.get("port", 5432) if db_choice else 5432

    if sys.platform == "win32":
        try:
            # Backend window — set DB env vars locally then start uvicorn.
            # NO space before `&&`: in cmd.exe `set VAR=value<space>&&` stores
            # the value INCLUDING that trailing space (so DB_HOST becomes
            # "localhost "), and asyncpg then fails getaddrinfo on the spaced
            # host → every DB query (login) 500s while /health still works.
            # Putting `&&` flush against the value keeps it clean. (Dogfood
            # 2026-06-01: this was the real "Incorrect email or password" —
            # the login endpoint was crashing, not rejecting credentials.)
            backend_cmd = (
                f"set DB_HOST=localhost&& set DB_PORT={db_port}&& "
                "uvicorn app.main:app --reload --host 0.0.0.0 --port 8000"
            )
            subprocess.Popen(
                f'start "CT Backend" cmd /k "{backend_cmd}"',
                shell=True, cwd=backend_dir,
            )
            # Frontend window — npm run dev (vite).
            subprocess.Popen(
                'start "CT Frontend" cmd /k "npm run dev"',
                shell=True, cwd=frontend_dir,
            )
            return True
        except OSError as exc:
            print(f"   ⚠️  เปิด terminal ใหม่ไม่สำเร็จ: {exc}")
            return False

    if sys.platform == "darwin":
        # AppleScript escapes — paths with backslashes break the script,
        # but macOS paths don't have backslashes in practice.
        backend_script = (
            f'cd "{backend_dir}" && '
            f"export DB_HOST=localhost DB_PORT={db_port} && "
            "uvicorn app.main:app --reload --host 0.0.0.0 --port 8000"
        )
        frontend_script = f'cd "{frontend_dir}" && npm run dev'
        try:
            subprocess.Popen([
                "osascript", "-e",
                f'tell application "Terminal" to do script "{backend_script}"',
            ])
            subprocess.Popen([
                "osascript", "-e",
                f'tell application "Terminal" to do script "{frontend_script}"',
            ])
            return True
        except OSError as exc:
            print(f"   ⚠️  เปิด Terminal.app ไม่สำเร็จ: {exc}")
            return False

    # Linux — try common terminal emulators
    import shutil as _shutil  # local import — mirrors pattern elsewhere
    backend_sh = (
        f'cd "{backend_dir}" && '
        f"export DB_HOST=localhost DB_PORT={db_port} && "
        "uvicorn app.main:app --reload --host 0.0.0.0 --port 8000; "
        'echo "Press Enter to close"; read'
    )
    frontend_sh = (
        f'cd "{frontend_dir}" && npm run dev; '
        'echo "Press Enter to close"; read'
    )
    for term in ("gnome-terminal", "konsole", "xfce4-terminal",
                 "x-terminal-emulator", "xterm"):
        if _shutil.which(term):
            try:
                if term == "gnome-terminal":
                    subprocess.Popen([term, "--", "bash", "-c", backend_sh])
                    subprocess.Popen([term, "--", "bash", "-c", frontend_sh])
                elif term == "konsole":
                    subprocess.Popen([term, "-e", "bash", "-c", backend_sh])
                    subprocess.Popen([term, "-e", "bash", "-c", frontend_sh])
                else:
                    subprocess.Popen([term, "-e", f"bash -c '{backend_sh}'"])
                    subprocess.Popen([term, "-e", f"bash -c '{frontend_sh}'"])
                return True
            except OSError as exc:
                print(f"   ⚠️  เปิด {term} ไม่สำเร็จ: {exc}")
                return False

    print("   ⚠️  ไม่พบ terminal emulator ที่รองรับ — กรุณาเปิด terminal เอง")
    return False


