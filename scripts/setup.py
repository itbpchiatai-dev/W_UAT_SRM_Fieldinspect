def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="setup.py",
        description="Chia Tai Web App Standard — Project Setup",
    )
    parser.add_argument(
        "--project-dir",
        dest="project_dir",
        default=None,
        help=(
            "Path ที่จะ scaffold project ไป (default: auto-detect). "
            "ใช้สำหรับ sibling-zip layout: --project-dir . จาก my-app/ ใหม่"
        ),
    )
    parser.add_argument(
        "--database-mode",
        choices=("new", "existing"),
        default="new",
        help=(
            "Database ownership mode (default: new). "
            "Use 'existing' to configure a connection without creating or migrating schema."
        ),
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    _ensure_utf8_stdio()
    args = _parse_args(argv)

    script_path = Path(__file__).resolve()
    root = _resolve_project_dir(script_path, args.project_dir)[0]

    # Guard: refuse to scaffold INTO the web-app-standard template repo
    if _is_template_dir(root):
        print("❌ ปฏิเสธ — target dir เป็น web-app-standard template เอง")
        print(f"   target: {root}")
        print()
        print("   การ scaffold ไปยังที่นี่จะเขียนทับ template repo. เลือกหนึ่งใน:")
        print()
        print("   Layout A (default):")
        print("     1. copy web-app-standard ไป folder ใหม่ (เช่น my-app/)")
        print("     2. cd my-app")
        print("     3. python scripts/setup.py")
        print()
        print("   Sibling-zip (advanced):")
        print("     1. สร้าง folder ใหม่ ข้าง ๆ web-app-standard/ (เช่น my-app/)")
        print("     2. cd my-app")
        print("     3. python ../web-app-standard/scripts/setup.py --project-dir .")
        print()
        return 1

    if not (root / "AGENTS.md").exists():
        # In sibling-zip layout we expect AGENTS.md to be copied during
        # scaffold. But Layout A requires AGENTS.md to already exist.
        # If the dir is fresh, that's fine — but we still need a sentinel.
        # We treat missing AGENTS.md as "fresh project dir" → ok, the
        # scaffolder will populate it. Warn but continue.
        if not _looks_like_fresh_project_dir(root):
            print(f"⚠️  AGENTS.md ไม่พบที่ {root} และ folder ไม่ว่าง")
            print("   กรุณารันจาก root ของ project หรือใช้ --project-dir <fresh-dir>")
            return 1

    # ตรวจ environment
    env = check_environment()
    if not handle_env_issues(env, database_mode=args.database_mode):
        return 1

    # ถาม project config
    try:
        cfg = collect_config(root)
    except (KeyboardInterrupt, EOFError):
        print("\n\nยกเลิก")
        return 130

    # ถาม DB
    db_name = cfg.project_slug.replace("-", "_")
    if args.database_mode == "existing":
        db_choice = choose_existing_database(db_name)
    else:
        db_choice = choose_database(
            db_name,
            env=env,
            auth_required=bool(cfg.bootstrap_admin_email),
        )

    # Confirm
    print("─" * 60)
    print()
    print(f"   Project: {cfg.project_display_name} ({cfg.project_slug})")
    print(f"   Owner:   {cfg.owner}  |  BU: {cfg.bu}")
    print(f"   Auth:    {cfg.auth_scope}")
    if db_choice.get("skip"):
        print("   DB:      ข้าม")
    elif db_choice.get("existing_database"):
        print(
            "   DB:      existing "
            f"{db_choice['host']}:{db_choice['port']}/{db_choice['db_name']}"
        )
        print("            schema setup: skipped (safe default)")
    elif db_choice.get("use_existing"):
        if db_choice.get("native"):
            print(f"   DB:      native PostgreSQL (port {db_choice['port']}, superuser: {db_choice.get('pg_user', 'postgres')})")
        else:
            print(f"   DB:      ใช้ {db_choice['container_name']} (port {db_choice['port']})")
        print(f"            database='{db_choice.get('db_name', db_name)}'  user='{db_choice.get('db_user', db_name)}'")
    else:
        print(f"   DB:      Docker container ใหม่ (port {db_choice.get('port', 5432)})")
        print(f"            database='{db_choice.get('db_name', db_name)}'  user='{db_choice.get('db_user', db_name)}'")
    print()
    if not _confirm("   ดำเนินการ?", default_yes=True):
        print("ยกเลิก")
        return 0

    print()

    # Generate files
    generate_files(cfg, root, db_choice)

    # Install + Start
    success = install_and_start(root, db_choice)

    # Register to CT App Registry
    print("── CT App Registry ───────────────────────────────────────")
    print()
    register_project(cfg, db_choice, root)
    print()

    # Auto-start dev servers — opens 2 new terminal windows so the user
    # sees uvicorn + vite logs without having to copy/paste commands.
    # Skip if install_and_start failed (servers would just crash and the
    # window-spam adds noise to an already-broken setup).
    servers_started = False
    if (
        success
        and not db_choice.get("skip")
        and not db_choice.get("existing_database")
    ):
        print("── Start Dev Servers ─────────────────────────────────────")
        print()
        if _confirm("   เปิด Backend + Frontend ใน terminal ใหม่เลยไหม?",
                    default_yes=True):
            servers_started = _spawn_dev_servers(root, db_choice)
            if servers_started:
                print("   ✅ Servers ถูกเปิดใน terminal ใหม่ 2 อันแล้ว")
            else:
                print("   ⚠️  Auto-start ไม่สำเร็จ — รันตามวิธีด้านล่างเอง")
        print()

    # Summary
    print_summary(cfg, servers_started=servers_started)

    if not success:
        print("  ⚠️  บางขั้นตอนมีปัญหา — ดู error ด้านบน")
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
