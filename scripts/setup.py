def _prompt_bootstrap_super_admin(cfg: ProjectConfig) -> None:
    """Ask for the first super-admin so seed.py can create the user.

    Internal-only / both → SSO is the natural default (Azure AD users
    auto-provision via JWKS verify; seed pre-creates the row + role).
    External-only → forces local auth + a real password (one-shot via
    env var AUTH_BOOTSTRAP_INITIAL_PASSWORD; never persisted).
    """
    print("── Bootstrap Super Admin ─────────────────────────────────")
    print()
    print("   user แรกของระบบ (role internal:super_admin)")
    print("   เปิดสิทธิ์ admin ทั้งหมด รวมถึงเพิ่ม role/user คนอื่น")
    print()

    while True:
        email = input("   Super admin email: ").strip()
        if not email:
            print("   ⚠️  จำเป็นต้องระบุ — admin คนแรกใช้สำหรับ login ครั้งแรก")
            continue
        if not _EMAIL_RE.match(email):
            print("   ⚠️  รูปแบบ email ไม่ถูกต้อง")
            continue
        cfg.bootstrap_admin_email = email.lower()
        break

    # Auth type — pick the default that GUARANTEES the admin can log in for
    # the chosen scope, so a user accepting defaults never locks themselves out:
    #   external_only → local  (SSO isn't available; seed enables local)
    #   internal_only → SSO     (seed disables local — a local admin would hit
    #                            "Local authentication is disabled" at /login)
    #   both          → local   (both enabled; local works without Azure config)
    if cfg.auth_scope == "external_only":
        cfg.bootstrap_admin_auth_type = "local"
        print("   Auth type:  local (external_only scope)")
    elif cfg.auth_scope == "internal_only":
        cfg.bootstrap_admin_auth_type = "sso"
        print("   Auth type:  SSO / Azure AD (internal_only scope)")
        print("   ⚠️  ต้องตั้งค่า Azure AD (client id/secret/tenant) ใน backend/.env")
        print("       ก่อน ไม่งั้น login ไม่ได้ — internal_only ปิด email/password ไว้")
    else:
        print()
        print("   Auth type ของ super admin:")
        print("     1. Local  — email + password (login ได้ทันที ไม่ต้องตั้ง Azure AD)")
        print("     2. SSO    — Azure AD (สำหรับ production ที่ตั้ง Azure AD แล้ว)")
        print()
        while True:
            t = input("   เลือก [1-2] (default: 1 Local): ").strip() or "1"
            if t == "1":
                cfg.bootstrap_admin_auth_type = "local"
                break
            if t == "2":
                cfg.bootstrap_admin_auth_type = "sso"
                break
            print("   ⚠️  กรุณาเลือก 1 หรือ 2")

    # Initial password (local only) — masked input shows '*' per char so the
    # user can tell typing is registering (stdlib getpass shows nothing).
    if cfg.bootstrap_admin_auth_type == "local":
        print()
        print("   Initial password สำหรับ super admin (≥ 12 ตัว, แสดง * ขณะพิมพ์)")
        print("   • ต้องผสม ≥ 2 ใน 4: ตัวพิมพ์ใหญ่ / เล็ก / ตัวเลข / สัญลักษณ์")
        print("   • ห้ามเป็นตัวอักษรล้วน/เลขล้วน, ลำดับ (123456789012), password ยอดฮิต")
        print("   • ใช้ครั้งเดียวตอน seed; ไม่ commit; เปลี่ยนได้ทันที่ login ครั้งแรก")
        # email local-part + project slug ห้ามโผล่ใน password (เดาง่ายสำหรับ deploy นี้)
        context_terms = [cfg.bootstrap_admin_email.split("@", 1)[0], cfg.project_slug]
        while True:
            pw = _getpass_masked("   Password: ")
            err = password_strength_error(pw, context_terms=context_terms)
            if err:
                print(f"   ⚠️  {err}")
                continue
            pw2 = _getpass_masked("   ยืนยัน password: ")
            if pw != pw2:
                print("   ⚠️  Password ไม่ตรงกัน — ลองใหม่")
                continue
            cfg.bootstrap_initial_password = pw
            break

    print()


